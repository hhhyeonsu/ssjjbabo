/**
 * 카탈로그에 등장하는 공정구분(공종)이 db.workTypes에 없으면 자동으로 추가합니다.
 * 이미 같은 이름의 공종이 있으면 건드리지 않습니다. 변경이 있으면 true를 반환합니다.
 */
function ensureSwWorkTypes(db){
  let changed = false;
  swCatalogCategories().forEach(cat=>{
    let wt = db.workTypes.find(w=>w.name===cat);
    if(!wt){
      wt = {id: uid('wt'), name: cat, category: '상하수도'};
      db.workTypes.push(wt);
      changed = true;
    }
    const hasCriteria = db.criteria.some(c=>c.workTypeId===wt.id);
    if(!hasCriteria){
      const d = SW_CATEGORY_DEFAULT_CRITERIA[cat] || SW_CATEGORY_DEFAULT_CRITERIA['토공사'];
      db.criteria.push({workTypeId: wt.id, ...d});
      changed = true;
    }
  });
  return changed;
}
